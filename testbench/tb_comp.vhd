			-- Clear only COMP's per-run state, retain the writable reference
			-- RAM, and compare the same utterance.  The newly enrolled slot has
			-- exact zero distance and must remap the result to digit 2.
			mode_record_in <= '0';
			clear_in <= '1';
			wait until rising_edge(clk);
			clear_in <= '0';
			wait until rising_edge(clk);

			for f in 0 to 62 loop
				frame_idx <= f;
				wait until rising_edge(clk) and ready_out = '1';
				start_in <= '1';
				wait until rising_edge(clk);
				start_in <= '0';
				wait until rising_edge(clk) and ready_out = '0';
				wait until rising_edge(clk) and ready_out = '1';
			end loop;

			wait for 5 * CLK_PERIOD;
			assert valid_out = '1'
				report "tb_comp recall run did not assert valid_out"
				severity failure;
			assert record_out = '0'
				report "tb_comp recall run incorrectly asserted record_out"
				severity failure;
			assert digit_out = x"2"
				report "tb_comp recall did not select the runtime-enrolled digit"
				severity failure;
			assert digit_idx3_patch = '0'
				report "tb_comp recall produced an unexpected digit-index patch"
				severity failure;

			write(L, string'("recall "));
			write(L, 1);
			write(L, string'(" "));
			write(L, to_integer(unsigned(digit_out)));
			write(L, string'(" "));
			write(L, 0);
			writeline(record_dump_file, L);

			finish;
		wait;
	end process;
end architecture;
