		variable L : line;
		variable value_i : integer;
		variable selected_digit_v : integer;
		variable selected_trial_v : integer;
		variable valid_i : integer;
		variable record_i : integer;
		variable idx3_i : integer;
	begin
		readline(spec_file, L);
		read(L, selected_digit_v);
		read(L, selected_trial_v);
		selected_digit_in <= std_logic_vector(to_unsigned(selected_digit_v, 5));
		selected_trial_in <= std_logic_vector(to_unsigned(selected_trial_v, 3));

		for f in 0 to 62 loop
			readline(dct_file, L);
			for c in 0 to 7 loop
				read(L, value_i);
				capture_dct_data(f)(c) <= value_i;
			end loop;
		end loop;

		for f in 0 to 62 loop
			readline(mel_file, L);
			for m in 0 to 31 loop
				read(L, value_i);
				capture_mel_data(f)(m) <= std_logic_vector(to_unsigned(value_i, 32));
			end loop;
		end loop;
		wait for 1 ns;

		reset_in <= '1';
		clear_in <= '0';
		start_in <= '0';
		mode_record_in <= '0';
		flush <= '0';
			wait for 8 * CLK_PERIOD;
		wait until rising_edge(clk);
		reset_in <= '0';
		wait until rising_edge(clk);

		for f in 0 to 62 loop
			frame_idx <= f;
			wait until rising_edge(clk) and ready_out = '1';
			start_in <= '1';
			wait until rising_edge(clk);
			start_in <= '0';
			wait until rising_edge(clk) and ready_out = '0';
			wait until rising_edge(clk) and ready_out = '1';
		end loop;

		wait for 5 * CLK_PERIOD;
		if valid_out = '1' then
			valid_i := 1;
		else
			valid_i := 0;
		end if;
		if record_out = '1' then
			record_i := 1;
		else
			record_i := 0;
		end if;
		if digit_idx3_patch = '1' then
			idx3_i := 1;
		else
			idx3_i := 0;
		end if;

		write(L, valid_i);
		write(L, string'(" "));
		write(L, to_integer(unsigned(digit_out)));
		write(L, string'(" "));
		write(L, idx3_i);
		write(L, string'(" "));
		write(L, record_i);
			writeline(dump_file, L);

			assert valid_out = '1'
				report "tb_comp initial compare did not assert valid_out"
				severity failure;
			assert record_out = '0'
				report "tb_comp initial compare incorrectly asserted record_out"
				severity failure;
			assert digit_out = x"9"
				report "tb_comp initial compare did not return digit 9"
				severity failure;

			-- Focused runtime-enrollment check.  Store the same captured
			-- 16-frame active window in digit 2, trial 1, without reloading the
			-- COE or resetting the reference BRAM.
			selected_digit_in <= std_logic_vector(to_unsigned(2, 5));
			selected_trial_in <= std_logic_vector(to_unsigned(1, 3));
			mode_record_in <= '1';
			clear_in <= '1';
			wait until rising_edge(clk);
			clear_in <= '0';
			wait until rising_edge(clk);

			for f in 0 to 62 loop
				frame_idx <= f;
				wait until rising_edge(clk) and ready_out = '1';
				start_in <= '1';
				wait until rising_edge(clk);
				start_in <= '0';
				wait until rising_edge(clk) and ready_out = '0';
				wait until rising_edge(clk) and ready_out = '1';
			end loop;

			wait for 5 * CLK_PERIOD;
			assert valid_out = '1'
				report "tb_comp record run did not assert valid_out"
				severity failure;
			assert record_out = '1'
				report "tb_comp record run did not assert record_out"
				severity failure;
			assert digit_out = x"2"
				report "tb_comp record run returned the wrong enrolled digit"
				severity failure;

			write(L, string'("record "));
			write(L, 1);
			write(L, string'(" "));
			write(L, to_integer(unsigned(digit_out)));
			write(L, string'(" "));
			write(L, 1);
