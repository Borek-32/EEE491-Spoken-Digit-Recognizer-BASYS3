architecture sim of tb_comp is
	constant CLK_PERIOD : time := 10 ns;
	constant DCT_DATA_LATENCY : integer := 3;
	constant MEL_DATA_LATENCY : integer := 3;
	type dct_addr_pipe_t is array (0 to DCT_DATA_LATENCY - 1) of std_logic_vector(2 downto 0);
	type mel_addr_pipe_t is array (0 to MEL_DATA_LATENCY - 1) of std_logic_vector(4 downto 0);
	signal clk          : std_logic := '0';
	signal reset_in     : std_logic := '1';
	signal clear_in     : std_logic := '0';
	signal start_in     : std_logic := '0';
	signal ready_out    : std_logic;
	signal dct_addr_out : std_logic_vector(2 downto 0);
	signal dct_data_in  : std_logic_vector(15 downto 0) := (others => '0');
	signal mel_addr_out : std_logic_vector(4 downto 0);
	signal mel_data_in  : std_logic_vector(31 downto 0) := (others => '0');
	signal selected_digit_in : std_logic_vector(4 downto 0) := "01001";
	signal selected_trial_in : std_logic_vector(2 downto 0) := "000";
	signal mode_record_in : std_logic := '0';
	signal record_out   : std_logic;
	signal flush        : std_logic := '0';
	signal flush_done   : std_logic;
	signal digit_out    : std_logic_vector(3 downto 0);
	signal valid_out    : std_logic;
	signal digit_idx3_patch : std_logic;
	signal frame_idx    : integer range 0 to 62 := 0;
	signal dct_addr_pipe : dct_addr_pipe_t := (others => (others => '0'));
	signal mel_addr_pipe : mel_addr_pipe_t := (others => (others => '0'));
	signal capture_dct_data : capture_dct_t := CAPTURE_DCT;
	signal capture_mel_data : capture_mel_t := CAPTURE_MEL;
begin
	clk <= not clk after CLK_PERIOD / 2;

	data_latency_model : process(clk)
	begin
		if rising_edge(clk) then
			dct_addr_pipe(0) <= dct_addr_out;
			for i in 1 to DCT_DATA_LATENCY - 1 loop
				dct_addr_pipe(i) <= dct_addr_pipe(i - 1);
			end loop;
			dct_data_in <= std_logic_vector(to_signed(
				capture_dct_data(frame_idx)(to_integer(unsigned(dct_addr_pipe(DCT_DATA_LATENCY - 1)))), 16));

			mel_addr_pipe(0) <= mel_addr_out;
			for i in 1 to MEL_DATA_LATENCY - 1 loop
				mel_addr_pipe(i) <= mel_addr_pipe(i - 1);
			end loop;
			mel_data_in <= capture_mel_data(frame_idx)(to_integer(unsigned(mel_addr_pipe(MEL_DATA_LATENCY - 1))));
		end if;
	end process;

	dut : entity work.COMP
		port map (
			reset_in     => reset_in,
			clock_in     => clk,
			clear_in     => clear_in,
			start_in     => start_in,
			ready_out    => ready_out,
			dct_addr_out => dct_addr_out,
			dct_data_in  => dct_data_in,
			mel_addr_out => mel_addr_out,
			mel_data_in  => mel_data_in,
			selected_digit_in => selected_digit_in,
			selected_trial_in => selected_trial_in,
			mode_record_in => mode_record_in,
			record_out   => record_out,
			flush        => flush,
			flush_done   => flush_done,
			digit_out    => digit_out,
			valid_out    => valid_out,
			digit_idx3_patch => digit_idx3_patch
		);

	stim : process
		file spec_file : text open read_mode is "../../../../verification/ref_data/tb_comp_ref.txt";
		file dct_file : text open read_mode is "../../../../verification/ref_data/tb_comp_dct_ref.txt";
			file mel_file : text open read_mode is "../../../../verification/ref_data/tb_comp_mel_ref.txt";
			file dump_file : text open write_mode is "../../../../verification/tb_output/tb_comp_output.txt";
